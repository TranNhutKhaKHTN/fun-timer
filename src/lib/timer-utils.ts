export function formatTime(ms: number) {
  const total = Math.floor(ms / 1000);
  const h = Math.floor(total / 3600);
  const m = Math.floor((total % 3600) / 60);
  const s = total % 60;
  const pad = (n: number) => String(n).padStart(2, "0");
  return h > 0 ? `${h}:${pad(m)}:${pad(s)}` : `${pad(m)}:${pad(s)}`;
}

export function isDarkColor(hex: string) {
  const n = parseInt(hex.slice(1), 16);
  const [r, g, b] = [(n >> 16) & 255, (n >> 8) & 255, n & 255];
  return (0.299 * r + 0.587 * g + 0.114 * b) / 255 < 0.45;
}

/** Tạo AudioContext trong lúc người dùng bấm nút để trình duyệt cho phép phát âm thanh về sau. */
export function unlockAudio(current: AudioContext | null) {
  let ctx = current;
  if (!ctx && typeof window !== "undefined" && "AudioContext" in window) ctx = new AudioContext();
  ctx?.resume();
  return ctx;
}

/** Tiếng "ting ting ting" khi hoàn thành, tạo bằng Web Audio nên không cần file âm thanh. */
export function playChime(ctx: AudioContext | null) {
  if (!ctx) return;
  const notes = [659.25, 783.99, 1046.5, 783.99, 1046.5];
  notes.forEach((freq, i) => {
    const osc = ctx.createOscillator();
    const gain = ctx.createGain();
    const t = ctx.currentTime + i * 0.18;
    osc.type = "triangle";
    osc.frequency.value = freq;
    gain.gain.setValueAtTime(0.0001, t);
    gain.gain.exponentialRampToValueAtTime(0.3, t + 0.02);
    gain.gain.exponentialRampToValueAtTime(0.0001, t + 0.5);
    osc.connect(gain).connect(ctx.destination);
    osc.start(t);
    osc.stop(t + 0.55);
  });
}
